const collectionBySlug = new Map(collections.map(collection => [collection.slug, collection]))

/** `category` is the collection's own title, so cards and filters always agree. */
export const products = catalogue.map(product => ({
  ...product,
  category: collectionBySlug.get(product.collection).title,
}))

export const getCollection = slug => collectionBySlug.get(slug)

export const productsByCollection = slug => products.filter(product => product.collection === slug)

export const findProduct = id => products.find(product => product.id === id)

/** One reel per collection on the home treat shelf. */
export const shelves = collections.map(collection => ({
  slug: collection.slug,
  category: collection.title,
  products: productsByCollection(collection.slug),
}))

